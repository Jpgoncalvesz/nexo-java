CREATE TABLE IF NOT EXISTS app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','VENDEDOR'))
);
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  price NUMERIC(12,2) NOT NULL CHECK (price > 0),
  stock INTEGER NOT NULL CHECK (stock BETWEEN 0 AND 1000000),
  minimum_stock INTEGER NOT NULL CHECK (minimum_stock BETWEEN 0 AND 1000000)
);
CREATE TABLE IF NOT EXISTS purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer VARCHAR(100) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE','CONFIRMADO','CANCELADO')),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_by VARCHAR(60) NOT NULL
);
CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES purchase_orders(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10000),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
  UNIQUE (order_id, product_id)
);
CREATE INDEX IF NOT EXISTS idx_orders_status_id ON purchase_orders(status,id DESC);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);
